from __future__ import annotations

from pathlib import Path

from api.config import settings


class LocalStorage:
    """Files in a local folder. At deployment a class with the same three methods will write
    to Cloudflare R2 instead, and nothing that uses `storage` has to change."""

    def __init__(self, root: str, url_prefix: str) -> None:
        self.root = Path(root).resolve()
        self.url_prefix = url_prefix.rstrip("/")
        self.root.mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        if self.root not in path.parents:  # defence in depth: keys are generated by the server
            raise ValueError("Invalid storage key")
        return path

    def save(self, key: str, data: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)

    def url(self, key: str) -> str:
        return f"{self.url_prefix}/{key}"


storage = LocalStorage(settings.media_dir, settings.media_url_prefix)